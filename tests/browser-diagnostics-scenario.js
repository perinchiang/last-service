 check('Integrity reflects actual damage',value('integrity')==='90%');
 for(const e of g.enemies.list)if(e.active)g.enemies.damage(e,200,e.group.position);
 step(3.2);for(const e of g.enemies.list)if(e.active)g.enemies.damage(e,200,e.group.position);g.step(.05,false);
